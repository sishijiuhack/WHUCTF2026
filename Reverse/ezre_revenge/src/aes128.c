static const uint8_t rcon[11] = {
    0x00, 0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40, 0x80, 0x1B, 0x36};

static uint8_t xtime(uint8_t x)
{
    return (uint8_t)((x << 1) ^ (((x >> 7) & 1u) * 0x1Bu));
}

static void aes_sub_bytes(uint8_t state[16])
{
    for (size_t i = 0; i < 16; ++i)
        state[i] = sbox[state[i]];
}

static void aes_shift_rows(uint8_t state[16])
{
    uint8_t tmp[16];

    tmp[0] = state[0];
    tmp[1] = state[5];
    tmp[2] = state[10];
    tmp[3] = state[15];

    tmp[4] = state[4];
    tmp[5] = state[9];
    tmp[6] = state[14];
    tmp[7] = state[3];

    tmp[8] = state[8];
    tmp[9] = state[13];
    tmp[10] = state[2];
    tmp[11] = state[7];

    tmp[12] = state[12];
    tmp[13] = state[1];
    tmp[14] = state[6];
    tmp[15] = state[11];

    memcpy(state, tmp, 16);
}

static void aes_mix_columns(uint8_t state[16])
{
    for (size_t c = 0; c < 4; ++c)
    {
        size_t i = c * 4;
        uint8_t a0 = state[i + 0];
        uint8_t a1 = state[i + 1];
        uint8_t a2 = state[i + 2];
        uint8_t a3 = state[i + 3];

        uint8_t t = a0 ^ a1 ^ a2 ^ a3;
        uint8_t u = a0;

        state[i + 0] ^= t ^ xtime((uint8_t)(a0 ^ a1));
        state[i + 1] ^= t ^ xtime((uint8_t)(a1 ^ a2));
        state[i + 2] ^= t ^ xtime((uint8_t)(a2 ^ a3));
        state[i + 3] ^= t ^ xtime((uint8_t)(a3 ^ u));
    }
}

static void aes_add_round_key(uint8_t state[16], const uint8_t *round_key)
{
    for (size_t i = 0; i < 16; ++i)
        state[i] ^= round_key[i];
}

static void aes_key_expansion(const uint8_t key[16], uint8_t round_keys[176])
{
    memcpy(round_keys, key, 16);

    size_t bytes_generated = 16;
    size_t rcon_iter = 1;
    uint8_t temp[4];

    while (bytes_generated < 176)
    {
        for (size_t i = 0; i < 4; ++i)
            temp[i] = round_keys[bytes_generated - 4 + i];

        if ((bytes_generated % 16) == 0)
        {
            uint8_t t = temp[0];
            temp[0] = temp[1];
            temp[1] = temp[2];
            temp[2] = temp[3];
            temp[3] = t;

            temp[0] = sbox[temp[0]];
            temp[1] = sbox[temp[1]];
            temp[2] = sbox[temp[2]];
            temp[3] = sbox[temp[3]];

            temp[0] ^= rcon[rcon_iter++];
        }

        for (size_t i = 0; i < 4; ++i)
        {
            round_keys[bytes_generated] = (uint8_t)(round_keys[bytes_generated - 16] ^ temp[i]);
            ++bytes_generated;
        }
    }
}

static void aes128_encrypt_block(uint8_t block[16], const uint8_t key[16])
{
    uint8_t round_keys[176];
    aes_key_expansion(key, round_keys);

    aes_add_round_key(block, round_keys);

    for (size_t round = 1; round <= 9; ++round)
    {
        aes_sub_bytes(block);
        aes_shift_rows(block);
        aes_mix_columns(block);
        aes_add_round_key(block, round_keys + round * 16);
    }

    aes_sub_bytes(block);
    aes_shift_rows(block);
    aes_add_round_key(block, round_keys + 160);
}

void aes128_encrypt_buffer(uint8_t buf[SHADOW_LEN], const uint8_t key[16])
{
    for (size_t off = 0; off < SHADOW_LEN; off += 16)
        aes128_encrypt_block(buf + off, key);
}
