static uint32_t prng_next(uint32_t *s)
{
    uint32_t x = *s;
    x ^= x << 13;
    x ^= x >> 17;
    x ^= x << 5;
    *s = x;
    return x;
}

static void shuffle_u16(uint16_t *arr, size_t n, uint32_t *seed)
{
    if (n <= 1)
        return;
    for (size_t i = n - 1; i > 0; --i)
    {
        size_t j = (size_t)(prng_next(seed) % (uint32_t)(i + 1));
        uint16_t t = arr[i];
        arr[i] = arr[j];
        arr[j] = t;
    }
}

static uint16_t dyn_mix(uint32_t kstate, uint16_t sid, uint32_t step)
{
    uint32_t v = kstate;
    v ^= (uint32_t)sid * 0x45D9u;
    v ^= step * 0x9E37u;
    return (uint16_t)(v & TABLE_MASK);
}

static uint32_t kstate_next(uint32_t kstate, uint16_t sid, uint8_t opcode, uint32_t step)
{
    uint32_t v = kstate;
    v ^= (uint32_t)sid * 0x1F5u;
    v ^= (uint32_t)opcode * 0x9E37u;
    v ^= step * 0xA3u;
    v = rol32(v, 7);
    v += 0x7F4A7C15u;
    return v;
}

