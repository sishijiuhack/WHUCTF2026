static size_t build_plain_program(Instr out[MAX_STATES])
{
    
    // _Static_assert(sizeof(plain_codes) % INSN_SIZE == 0, "plain bytecode is truncated");
    // _Static_assert(sizeof(plain_codes) / INSN_SIZE <= MAX_STATES, "plain bytecode exceeds MAX_STATES");

    uint8_t *decoded = (uint8_t *)out;
    for (size_t i = 0; i < sizeof(plain_codes); ++i)
        decoded[i] = (uint8_t)(plain_codes[i] ^ (uint8_t)i);

    return sizeof(plain_codes) / INSN_SIZE;
}

void vm_build_real_target(uint8_t out[REAL_TARGET_LEN])
{
    static const uint8_t enc_target[REAL_TARGET_LEN] = {
        0x02, 0xD2, 0xAD, 0x8F, 0x35, 0xC8, 0x75, 0x8E,
        0xD9, 0x5F, 0xA4, 0xF3, 0x43, 0x52, 0x29, 0xAD,
        0x88, 0xDE, 0x46, 0xAA, 0x56, 0x11, 0xE5, 0xF9,
        0xD8, 0xD6, 0x18, 0xA7, 0x4E, 0x73, 0xA7, 0xCA};

    for (size_t i = 0; i < REAL_TARGET_LEN; ++i)
    {
        out[i] = (uint8_t)(enc_target[i] ^ stream_byte(0xC0DEC0DEu, i));
    }
}

static void build_program(VMProgram *p)
{
    // 生成原始程序字节码
    Instr plain[MAX_STATES];
    size_t n = build_plain_program(plain);

    memset(p, 0, sizeof(*p));
    p->state_count = n;
    // 将所有状态号初始化为无效（对应的存储槽位无效）
    for (size_t i = 0; i < TABLE_SIZE; ++i)
        p->sid_to_slot[i] = 0xFFFFu;

    // 后面所有 shuffle_u16() 的初始种子
    uint32_t seed = 0x5A17C0DEu;

    // 1. 给每个逻辑指令分配状态号
    uint16_t sid_pool[TABLE_SIZE];
    for (size_t i = 0; i < TABLE_SIZE; ++i)
        sid_pool[i] = (uint16_t)i;
    shuffle_u16(sid_pool, TABLE_SIZE, &seed);
    for (size_t i = 0; i < n; ++i)
        p->logical_to_sid[i] = sid_pool[i];

    // 2. 给每个状态号分配存储槽位
    uint16_t slot_pool[MAX_STATES];
    for (size_t i = 0; i < n; ++i)
        slot_pool[i] = (uint16_t)i;
    shuffle_u16(slot_pool, n, &seed);
    for (size_t i = 0; i < n; ++i)
    {
        uint16_t sid = p->logical_to_sid[i];
        p->sid_to_slot[sid] = slot_pool[i];
    }

    // 3. 构造状态置换表和逆置换表
    uint16_t state_perm[TABLE_SIZE];
    for (size_t i = 0; i < TABLE_SIZE; ++i)
        state_perm[i] = (uint16_t)i;
    shuffle_u16(state_perm, TABLE_SIZE, &seed);

    for (size_t i = 0; i < TABLE_SIZE; ++i)
    {
        p->state_table[i] = state_perm[i];
        p->inv_state_table[state_perm[i]] = (uint16_t)i;
    }

    // 获取起始状态号和终止状态号
    p->start_sid = p->logical_to_sid[0];
    p->halt_sid = p->logical_to_sid[n - 1];

    // 初始化kstate状态变量
    uint32_t k_expect = 0xD00D1234u;

    // 循环处理每条指令
    for (size_t i = 0; i < n; ++i)
    {
        // 计算当前指令和下一条指令的sid，最后一条指令的下一条指令是自己
        uint16_t sid = p->logical_to_sid[i];
        uint16_t desired_next = (i + 1 < n) ? p->logical_to_sid[i + 1] : sid;

        Instr cur = plain[i];
        // 如果是跳转指令，就将需要跳转到的指令地址部分patch成对应的状态号
        if (cur.opcode == OP_JNZ || cur.opcode == OP_JMP)
        {
            uint16_t target_logical = imm16(cur.op2, cur.op3);
            uint16_t target_sid = p->logical_to_sid[target_logical];
            cur.op2 = (uint8_t)(target_sid & 0xFFu);
            cur.op3 = (uint8_t)(target_sid >> 8);
        }

        // 计算一个动态扰动值
        uint16_t dyn = dyn_mix(k_expect, sid, (uint32_t)i);
        p->edge_token[sid] = (uint16_t)(p->inv_state_table[desired_next] ^ dyn);

        // 计算当前指令对应的槽位
        uint16_t slot = p->sid_to_slot[sid];
        uint8_t raw[4] = {cur.opcode, cur.op1, cur.op2, cur.op3};
        for (size_t b = 0; b < INSN_SIZE; ++b)
        {
            size_t idx = (size_t)slot * INSN_SIZE + b;
            uint32_t local_seed = 0x31415926u ^ ((uint32_t)sid << 16) ^ ((uint32_t)slot << 3);
            uint8_t k = stream_byte(local_seed, idx);
            // 生成一个伪随机字节，并与指令进行逐字节异或
            p->enc_code[idx] = (uint8_t)(raw[b] ^ k);
        }

        k_expect = kstate_next(k_expect, sid, cur.opcode, (uint32_t)i);
    }

    p->built = 1;
}

void vm_program_ensure_ready(VMProgram *program)
{
    if (!program->built)
        build_program(program);
}

static int decode_instruction(const VMProgram *p, const VM *vm, Instr *out)
{
    uint16_t sid = vm->sid;
    if (sid >= TABLE_SIZE)
        return 0;
    uint16_t slot = p->sid_to_slot[sid];
    if (slot == 0xFFFFu || slot >= p->state_count)
        return 0;

    uint8_t tmp[4];
    for (size_t b = 0; b < INSN_SIZE; ++b)
    {
        size_t idx = (size_t)slot * INSN_SIZE + b;
        uint32_t local_seed = 0x31415926u ^ ((uint32_t)sid << 16) ^ ((uint32_t)slot << 3);
        uint8_t k = stream_byte(local_seed, idx);
        tmp[b] = (uint8_t)(p->enc_code[idx] ^ k);
    }

    out->opcode = tmp[0];
    out->op1 = tmp[1];
    out->op2 = tmp[2];
    out->op3 = tmp[3];
    return 1;
}

typedef void (*OpHandler)(VM *, const Instr *);

static void op_invalid(VM *vm, const Instr *in)
{
    (void)in;
    vm->trap = 0xBAD0u;
    vm->running = 0;
}

static void op_movi(VM *vm, const Instr *in)
{
    if (in->op1 < REG_CNT)
        vm->reg[in->op1] = imm16(in->op2, in->op3);
}

static void op_load(VM *vm, const Instr *in)
{
    uint16_t addr = imm16(in->op2, in->op3);
    if (in->op1 < REG_CNT && addr < MEM_SIZE)
        vm->reg[in->op1] = vm->mem[addr];
}

static void op_store(VM *vm, const Instr *in)
{
    uint16_t addr = imm16(in->op2, in->op3);
    if (in->op1 < REG_CNT && addr < MEM_SIZE)
        vm->mem[addr] = (uint8_t)(vm->reg[in->op1] & 0xFFu);
}

static void op_add(VM *vm, const Instr *in)
{
    if (in->op1 < REG_CNT && in->op2 < REG_CNT)
        vm->reg[in->op1] += vm->reg[in->op2];
}

static void op_addi(VM *vm, const Instr *in)
{
    if (in->op1 < REG_CNT)
        vm->reg[in->op1] += in->op2;
}

static void op_xori(VM *vm, const Instr *in)
{
    if (in->op1 < REG_CNT)
        vm->reg[in->op1] ^= in->op2;
}

static void op_shl(VM *vm, const Instr *in)
{
    if (in->op1 < REG_CNT)
        vm->reg[in->op1] <<= (in->op2 & 31u);
}

static void op_shr(VM *vm, const Instr *in)
{
    if (in->op1 < REG_CNT)
        vm->reg[in->op1] >>= (in->op2 & 31u);
}

static void op_cmp(VM *vm, const Instr *in)
{
    if (in->op1 < REG_CNT && in->op2 < REG_CNT)
        vm->zf = (vm->reg[in->op1] == vm->reg[in->op2]) ? 1u : 0u;
    else
        vm->zf = 0;
}

static void op_jnz(VM *vm, const Instr *in)
{
    if (!vm->zf)
    {
        vm->branch_override = 1;
        vm->branch_sid = imm16(in->op2, in->op3);
    }
}

static void op_jmp(VM *vm, const Instr *in)
{
    vm->branch_override = 1;
    vm->branch_sid = imm16(in->op2, in->op3);
}

static void op_halt(VM *vm, const Instr *in)
{
    (void)in;
    vm->running = 0;
}

static void op_loadr(VM *vm, const Instr *in)
{
    if (in->op1 < REG_CNT && in->op2 < REG_CNT)
    {
        uint32_t addr = vm->reg[in->op2];
        if (addr < MEM_SIZE)
            vm->reg[in->op1] = vm->mem[addr];
    }
}

static void op_storer(VM *vm, const Instr *in)
{
    if (in->op1 < REG_CNT && in->op2 < REG_CNT)
    {
        uint32_t addr = vm->reg[in->op2];
        if (addr < MEM_SIZE)
            vm->mem[addr] = (uint8_t)(vm->reg[in->op1] & 0xFFu);
    }
}

static void op_incr(VM *vm, const Instr *in)
{
    if (in->op1 < REG_CNT)
        vm->reg[in->op1]++;
}

static void op_mov(VM *vm, const Instr *in)
{
    if (in->op1 < REG_CNT && in->op2 < REG_CNT)
        vm->reg[in->op1] = vm->reg[in->op2];
}

static void op_xor(VM *vm, const Instr *in)
{
    if (in->op1 < REG_CNT && in->op2 < REG_CNT)
        vm->reg[in->op1] ^= vm->reg[in->op2];
}

static void op_rol(VM *vm, const Instr *in)
{
    if (in->op1 < REG_CNT)
        vm->reg[in->op1] = rol32(vm->reg[in->op1], in->op2 & 31u);
}

void vm_init(VM *vm, const VMProgram *p)
{
    memset(vm, 0, sizeof(*vm));
    vm->running = 1;
    vm->sid = p->start_sid;
    vm->kstate = 0xD00D1234u;
    vm->cstate = 0xA17E5EEDu;
}

void vm_exec(VM *vm, const VMProgram *p)
{
    static OpHandler handlers[0x20] = {
        op_invalid,
        op_movi,
        op_load,
        op_store,
        op_add,
        op_addi,
        op_xori,
        op_shl,
        op_shr,
        op_cmp,
        op_jnz,
        op_jmp,
        op_halt,
        op_loadr,
        op_storer,
        op_incr,
        op_mov,
        op_xor,
        op_rol};

    while (vm->running)
    {
        if (vm->step > STEP_LIMIT)
        {
            vm->trap = 0xEEEEu;
            vm->running = 0;
            break;
        }

        Instr in;
        uint16_t cur_sid = vm->sid;
        if (!decode_instruction(p, vm, &in))
        {
            vm->trap = 0xDEADu;
            vm->running = 0;
            break;
        }

        vm->branch_override = 0;
        size_t opcode = in.opcode;
        if (opcode < (sizeof(handlers) / sizeof(handlers[0])) && handlers[opcode] != NULL)
            handlers[opcode](vm, &in);
        else
            op_invalid(vm, &in);

        if (!vm->running)
            break;

        if (vm->branch_override)
        {
            vm->sid = vm->branch_sid;
        }
        else
        {
            uint16_t dyn = dyn_mix(vm->kstate, cur_sid, vm->step);
            uint16_t idx = (uint16_t)(p->edge_token[cur_sid] ^ dyn);
            idx &= TABLE_MASK;
            vm->sid = p->state_table[idx];
        }

        vm->cstate = cstate_next(vm->cstate, cur_sid, in.opcode, vm->reg[1]);
        vm->kstate = kstate_next(vm->kstate, cur_sid, in.opcode, vm->step);
        vm->step++;
    }
}
